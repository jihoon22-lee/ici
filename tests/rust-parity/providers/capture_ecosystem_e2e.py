"""Capture frozen `ici analyze` on real ESLint/tsc/Clippy (development-only oracle).

Usage: capture_ecosystem_e2e.py <oracle-src> <python> <work-dir> <out.json>
PATH must expose eslint, tsc and cargo; the work directory must be outside /tmp
because Cargo writes its target directory below the project.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

FILES = {
    "ici.toml": 'schema_version=1\n[workspace]\nname="eco"\nprofile="standard"\n'
    '[[components]]\nid="web"\nroot="."\nlanguages=["javascript","typescript","rust"]\n',
    "eslint.config.mjs": 'export default [{files:["**/*.js","**/*.ts"],'
    'rules:{"no-unused-vars":"error",eqeqeq:"warn"}}];\n',
    "src/a.js": "const x = 1;\nif (globalThis.a == 2) { console.log(1); }\n",
    "src/b.ts": "interface A { x: number; y: string }\nconst v: A = { x: 1 };\n"
    'const n: number = "s";\nexport { v, n };\n',
    "src/c.ts": "const z = 1;\nexport {};\n",
    "tsconfig.json": '{"compilerOptions":{"strict":true,"noEmit":true},"include":["src/**/*.ts"]}\n',
    "Cargo.toml": '[package]\nname="eco"\nversion="0.1.0"\nedition="2021"\n'
    '[lib]\npath="src/lib.rs"\n\n[workspace]\n',
    "Cargo.lock": "# This file is automatically @generated by Cargo.\n"
    "# It is not intended for manual editing.\nversion = 4\n\n"
    '[[package]]\nname = "eco"\nversion = "0.1.0"\n',
    "src/lib.rs": "pub fn f(a: i32) -> i32 {\n    return a + 1;\n}\n",
}


def main() -> None:
    oracle, python, work, out = (Path(item) for item in sys.argv[1:5])
    project = work / "ecosystem-oracle"
    shutil.rmtree(project, ignore_errors=True)
    for name, text in FILES.items():
        (project / name).parent.mkdir(parents=True, exist_ok=True)
        (project / name).write_text(text, encoding="utf-8")
    env = dict(os.environ, PYTHONPATH=str(oracle))
    completed = subprocess.run(
        [str(python), "-m", "ici", "analyze", "--json", "--result", "result.json"],
        cwd=project,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    result = json.loads((project / "result.json").read_text(encoding="utf-8"))
    document = {
        "source": "6fe3e405f8e584234a56cb8f0d8c0bd2cb31a188",
        "files": FILES,
        "exit": completed.returncode,
        "checks": {item["check_id"]: item["state"] for item in result["checks"]},
        "findings": sorted(
            (
                {
                    "rule_id": item["rule_id"],
                    "path": item["primary_location"]["path"],
                    "line": item["primary_location"]["start_line"],
                    "column": item["primary_location"].get("start_column"),
                    "message": item["message"],
                    "fingerprint": item["fingerprint"],
                }
                for item in result["findings"]
            ),
            key=lambda item: (item["path"], item["line"], item["rule_id"]),
        ),
    }
    out.write_text(json.dumps(document, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    shutil.rmtree(project)


if __name__ == "__main__":
    main()
