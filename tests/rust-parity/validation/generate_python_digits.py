"""Development-only generator of crates/ici-validation/src/python_digits.rs; never called by Rust.

    /home/jihoon/projects/ici/.venv/bin/python -I -B generate_python_digits.py

Root ruling 2026-11-14 (legacy gcov text numbers follow frozen): frozen
analysis/coverage_support.py reads gcov text numbers with `str.isdigit()` and `int()` on the
frozen interpreter, CPython 3.10.21 with Unicode 13.0.0. Rust's own Unicode tables are newer, so
the two character classes those calls use are written out from that interpreter:
- `DECIMAL`: `str.isdecimal()` characters, the ones `int()` maps to a digit value;
- `DIGIT_ONLY`: `str.isdigit()` characters that are not decimal (superscripts, circled digits),
  which `isdigit()` accepts and `int()` refuses with ValueError.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

assert sys.version_info[:3] == (3, 10, 21), sys.version
assert unicodedata.unidata_version == "13.0.0", unicodedata.unidata_version
TARGET = Path(__file__).resolve().parents[3] / "crates/ici-validation/src/python_digits.rs"

decimal: list[list[int]] = []
digit_only: list[list[int]] = []
for code in range(0x110000):
    character = chr(code)
    if character.isdecimal():
        value = int(character)
        assert character.isdigit() and unicodedata.decimal(character) == value
        last = decimal[-1] if decimal else None
        if last and last[1] == code - 1 and last[2] + (code - last[0]) == value:
            last[1] = code
        else:
            decimal.append([code, code, value])
    elif character.isdigit():
        if digit_only and digit_only[-1][1] == code - 1:
            digit_only[-1][1] = code
        else:
            digit_only.append([code, code])
decimal_count = sum(last - first + 1 for first, last, _ in decimal)
digit_count = sum(last - first + 1 for first, last in digit_only)
lines = [
    "//! Generated by tests/rust-parity/validation/generate_python_digits.py from CPython "
    f"{sys.version.split()[0]}",
    f"//! (unicodedata {unicodedata.unidata_version}); do not edit.",
    "",
    f"/// `str.isdecimal()` characters ({decimal_count}): `(first, last, value of first)`, the",
    "/// value ascending by one over each range.",
    "pub(crate) const DECIMAL: &[(u32, u32, u8)] = &[",
    *(f"    (0x{first:05X}, 0x{last:05X}, {value})," for first, last, value in decimal),
    "];",
    "",
    f"/// `str.isdigit()` characters that are not decimal ({digit_count}): `(first, last)`.",
    "pub(crate) const DIGIT_ONLY: &[(u32, u32)] = &[",
    *(f"    (0x{first:05X}, 0x{last:05X})," for first, last in digit_only),
    "];",
    "",
]
TARGET.write_text("\n".join(lines), encoding="utf-8")
print(TARGET, decimal_count, digit_count)
